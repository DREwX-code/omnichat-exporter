  function normalizeLocale(locale) {
    return String(locale || "")
      .trim()
      .replace(/_/g, "-");
  }

  function matchLocale(locale) {
    const normalized = normalizeLocale(locale);
    if (!normalized) {
      return "";
    }
    const lower = normalized.toLowerCase();
    if (localeByLowerCase[lower]) {
      return localeByLowerCase[lower];
    }
    const parts = lower.split("-");
    const language = parts[0];
    const region = parts[1] || "";
    if (language === "zh") {
      return region === "tw" ||
        region === "hk" ||
        region === "mo" ||
        lower.includes("hant")
        ? "zh-TW"
        : "zh-CN";
    }
    if (language === "es" && latinAmericanSpanishRegions.has(region)) {
      return "es-419";
    }
    return localeByLowerCase[language] || "";
  }

  function detectLocale(preferredLocales) {
    const candidates =
      Array.isArray(preferredLocales) && preferredLocales.length
        ? preferredLocales
        : typeof navigator !== "undefined" &&
          Array.isArray(navigator.languages) &&
          navigator.languages.length
          ? navigator.languages
          : [typeof navigator !== "undefined" ? navigator.language : "en"];
    for (const candidate of candidates) {
      const matched = matchLocale(candidate);
      if (matched) {
        return matched;
      }
    }
    return "en";
  }

  const activeLocale = detectLocale();
  const activeDirection = /^(ar|he|ug|ckb)(-|$)/i.test(activeLocale)
    ? "rtl"
    : "ltr";

  function interpolate(template, variables) {
    return Object.keys(variables || {}).reduce((text, name) => {
      return text.replace(
        new RegExp(`\\{${name}\\}`, "g"),
        String(variables[name]),
      );
    }, template);
  }

  function translate(key, variables, locale) {
    const selectedLocale = matchLocale(locale) || activeLocale;
    const dictionary = translations[selectedLocale] || translations.en;
    const template = dictionary[key] || translations.en[key] || key;
    return interpolate(template, variables);
  }

